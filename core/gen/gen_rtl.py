import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from kuznechik_ref import PI, _L

out = os.path.join(os.path.dirname(__file__), "..", "rtl")

rows = "\n".join("            8'h%02X: y = 8'h%02X;" % (i, PI[i]) for i in range(256))
open(os.path.join(out, "kuz_sbox.v"), "w").write("""// GENERATED by gen/gen_rtl.py - do not edit.
// GOST R 34.12-2015 "Kuznyechik" S-box (pi).
module kuz_sbox (
    input  wire [7:0] a,
    output reg  [7:0] y
);
    always @* begin
        case (a)
%s
            default: y = 8'h00;
        endcase
    end
endmodule
""" % rows)

cols = []
for bit in range(128):
    v = (1 << bit).to_bytes(16, "big")
    cols.append(int.from_bytes(_L(v), "big"))
masks = []
for obit in range(128):
    m = 0
    for ibit in range(128):
        if (cols[ibit] >> obit) & 1:
            m |= 1 << ibit
    masks.append(m)
lines = "\n".join("    assign y[%d] = ^(x & 128'h%032X);" % (i, masks[i]) for i in range(128))
open(os.path.join(out, "kuz_lin.v"), "w").write("""// GENERATED by gen/gen_rtl.py - do not edit.
// GOST R 34.12-2015 "Kuznyechik" linear transform L (= R^16),
// flattened to a 128x128 matrix over GF(2): every output bit is the
// XOR of the input bits selected by a constant mask.
module kuz_lin (
    input  wire [127:0] x,
    output wire [127:0] y
);
%s
endmodule
""" % lines)

rc = "\n".join("            6'd%d: kuz_rcon = 128'h%s;" % (i, _L(bytes(15) + bytes([i])).hex().upper())
               for i in range(1, 33))
open(os.path.join(out, "kuz_rcon.vh"), "w").write("""// GENERATED by gen/gen_rtl.py - do not edit.
// Key schedule constants C_i = L(Vec_128(i)), i = 1..32.
function [127:0] kuz_rcon;
    input [5:0] i;
    begin
        case (i)
%s
            default: kuz_rcon = 128'h0;
        endcase
    end
endfunction
""" % rc)
print("generated kuz_sbox.v, kuz_lin.v, kuz_rcon.vh; avg XOR fan-in of L: %.1f" % (sum(bin(m).count("1") for m in masks) / 128))
